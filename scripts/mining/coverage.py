#!/usr/bin/env python3
"""Coverage report: which places are thin and which source families are missing where.

Usage: python3 scripts/mining/coverage.py          write pipeline/coverage.json and docs/COVERAGE.md
       python3 scripts/mining/coverage.py --check  exit 1 if either file is out of date (CI runs this)

Reads pipeline/registry.json, data/local-programs.json and data/world.json. The "next batch" lists at the end of the
report are the queue: the thinnest places first, then the families missing in the most places.
"""
import json, re, sys
from collections import Counter
from common import LOCAL, PLACES, ROOT, WORLD, load, registry

COV_JSON = ROOT / 'pipeline' / 'coverage.json'
COV_MD = ROOT / 'docs' / 'COVERAGE.md'


def build():
    reg = registry(); recs = load(LOCAL)['records']; world = load(WORLD)
    us_fams = [f for f in reg['families'] if f['applies_to'] == 'us']
    w_fams = [f for f in reg['families'] if f['applies_to'] == 'country']
    by_place = {p: [r for r in recs if r['state'] == p] for p in PLACES}
    us = {}
    for p, rs in by_place.items():
        fams = {}
        for f in us_fams:
            idre = re.compile(f['match']['id'], re.I); nre = re.compile(f['match']['name'], re.I) if f['match'].get('name') else None
            ids = set(f['match'].get('ids', []))
            n = sum(1 for r in rs if r.get('family') == f['id'] or r['id'] in ids or (
                (not f['match'].get('same_category') or r['category'] == f['category'])
                and (idre.search(r['id']) or (nre and nre.search(r['name'])))))
            fams[f['id']] = n
        missing = [f['id'] for f in us_fams if fams[f['id']] < f['expect']]
        us[p] = {'name': PLACES[p], 'listings': len(rs), 'county_listings': sum(1 for r in rs if r['scope'] == 'counties'),
                 'by_category': dict(sorted(Counter(r['category'] for r in rs).items())), 'families': fams,
                 'missing': missing, 'score': round(1 - len(missing) / len(us_fams), 2)}
    countries = {}
    for c in world['countries']:
        secs = Counter(r['section'] for r in c['resources'])
        missing = [f['section'] for f in w_fams if secs[f['section']] < f['expect']]
        countries[c['code']] = {'name': c['name'], 'listings': len(c['resources']), 'by_section': dict(sorted(secs.items())),
                                'missing': missing, 'directory_only': sum(1 for r in c['resources'] if r.get('record_status') == 'directory_listed')}
    gaps = Counter(m for v in us.values() for m in v['missing'])
    wgaps = Counter(m for v in countries.values() for m in v['missing'])
    status = Counter(r.get('record_status') or 'unset' for r in recs)
    return {'registry_updated_on': reg['updated_on'],
            'us_summary': {'places': len(us), 'listings': len(recs), 'evidence': dict(sorted(status.items())),
                           'family_gaps': dict(gaps.most_common())},
            'world_summary': {'countries': len(countries), 'listings': sum(v['listings'] for v in countries.values()),
                              'section_gaps': dict(wgaps.most_common())},
            'us': us, 'countries': countries}


def markdown(cov):
    reg = registry(); fam_label = {f['id']: f['label'] for f in reg['families']}
    us, cs = cov['us'], cov['countries']
    L = ['# Coverage report', '',
         'Generated by `scripts/mining/coverage.py` from `pipeline/registry.json`, `data/local-programs.json` and `data/world.json`. Do not edit by hand; rerun the script. How the pipeline works: `docs/DATA-PIPELINE.md`.', '',
         f"United States and territories: {cov['us_summary']['listings']:,} listings in {cov['us_summary']['places']} places. "
         f"Other countries: {cov['world_summary']['listings']:,} listings in {cov['world_summary']['countries']} countries.", '',
         '## Evidence levels (US listings)', '']
    for k, v in cov['us_summary']['evidence'].items(): L.append(f'- `{k}`: {v:,}')
    L += ['', '## US source families: places still missing each', '', '| Family | Places missing |', '|---|---|']
    for f in reg['families']:
        if f['applies_to'] != 'us': continue
        miss = sorted(p for p, v in us.items() if f['id'] in v['missing'])
        L.append(f"| {f['label']} (needs {f['expect']}) | {len(miss)}: {', '.join(miss) if len(miss) <= 20 else ', '.join(miss[:20]) + ', ...'} |")
    L += ['', '## Thinnest US places', '', '| Place | Listings | County-level | Families met | Missing |', '|---|---|---|---|---|']
    for p, v in sorted(us.items(), key=lambda kv: (kv[1]['score'], kv[1]['listings']))[:20]:
        L.append(f"| {v['name']} ({p}) | {v['listings']} | {v['county_listings']} | {v['score']:.0%} | {', '.join(v['missing']) or 'none'} |")
    L += ['', '## Countries: sections still missing', '', '| Section | Countries missing |', '|---|---|']
    for f in reg['families']:
        if f['applies_to'] != 'country': continue
        L.append(f"| {f['label']} | {sum(1 for v in cs.values() if f['section'] in v['missing'])} |")
    L += ['', '## Thinnest countries', '', '| Country | Listings | Missing sections |', '|---|---|---|']
    for code, v in sorted(cs.items(), key=lambda kv: (kv[1]['listings'], -len(kv[1]['missing']), kv[0]))[:30]:
        L.append(f"| {v['name']} ({code}) | {v['listings']} | {', '.join(v['missing']) or 'none'} |")
    L += ['', '## Next batch (the queue)', '',
          'Work these first. Each line is a family missing in the most places; the place lists above say where.', '']
    for fid, n in list(cov['us_summary']['family_gaps'].items())[:8]:
        L.append(f'- US: {fam_label[fid]}, missing in {n} places')
    for sec, n in cov['world_summary']['section_gaps'].items():
        L.append(f'- Countries: {fam_label["world-" + sec]}, missing in {n} countries')
    return '\n'.join(L) + '\n'


def main():
    cov = build(); js = json.dumps(cov, indent=1, ensure_ascii=False) + '\n'; md = markdown(cov)
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in ((COV_JSON, js), (COV_MD, md)) if not p.exists() or p.read_text(encoding='utf-8') != t]
        if stale: sys.exit('Coverage report out of date, run python3 scripts/mining/coverage.py: ' + ', '.join(stale))
        print('coverage report up to date'); return
    COV_JSON.write_text(js, encoding='utf-8'); COV_MD.write_text(md, encoding='utf-8')
    print('US family gaps:', cov['us_summary']['family_gaps']); print('Country section gaps:', cov['world_summary']['section_gaps'])


if __name__ == '__main__':
    main()
